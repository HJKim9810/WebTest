function pickDistractors(rows, index, valueSelector) {
  const blockSize = 5;
  const blockStart = Math.floor(index / blockSize) * blockSize;
  const preferred = [];

  for (let i = blockStart; i < Math.min(blockStart + blockSize, rows.length); i += 1) {
    if (i !== index) preferred.push(i);
  }

  for (let distance = 1; preferred.length < 3 && distance < rows.length; distance += 1) {
    const before = index - distance;
    const after = index + distance;
    if (before >= 0 && before !== index) preferred.push(before);
    if (after < rows.length && after !== index) preferred.push(after);
  }

  return preferred.slice(0, 3).map((candidateIndex) => valueSelector(rows[candidateIndex]));
}

function buildDefinitionChoiceQuestion(subject, subjectName, index, rows) {
  const [topic, answer] = rows[index];
  const id = `${subject}-${String(index + 1).padStart(3, "0")}`;
  const distractors = pickDistractors(rows, index, (row) => row[1]);
  return {
    id,
    subject,
    subjectName,
    topic,
    difficulty: index < 15 ? "basic" : index < 30 ? "normal" : "review",
    question: `다음 중 '${topic}'에 대한 설명으로 가장 적절한 것은?`,
    choices: [answer, ...distractors],
    answer,
    explanation: `${topic}: ${answer}`,
  };
}

function buildTermChoiceQuestion(subject, subjectName, index, rows) {
  const [topic, answer] = rows[index];
  const id = `${subject}-${String(index + 1).padStart(3, "0")}`;
  const distractors = pickDistractors(rows, index, (row) => row[0]);
  return {
    id,
    subject,
    subjectName,
    topic,
    difficulty: index < 15 ? "basic" : index < 30 ? "normal" : "review",
    question: `다음 설명에 해당하는 용어로 가장 적절한 것은? ${answer}`,
    choices: [topic, ...distractors],
    answer: topic,
    explanation: `${topic}: ${answer}`,
  };
}

